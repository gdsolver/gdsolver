"""Writes dp/src/dp/collide_tmpl.gen.hpp: a player image (cube standing on the floor in a classic level) and the layer words the shadow starts from."""
import csv, struct, sys

base = sys.argv[2]   # the contact-pass trace (ctraw.csv) of a classic level
out = sys.argv[1]
want = 200
for row in csv.reader(open(base, newline="")):
    try:
        t = int(row[1])
    except Exception:
        continue
    if t == want:
        parts = row[6].split(";")
        img = bytearray(bytes.fromhex(parts[0]))
        # pointer fields hold uids in the harness' convention: clear them
        for off in (0x5e8, 0x5f0, 0x600, 0x608, 0x610, 0x618, 0x678, 0x680, 0x890):
            img[off:off + 8] = b"\0" * 8
        lay = [bytes.fromhex(p) for p in parts[2:7]]
        pq = parts[7].split(":")
        f = lambda b, o: struct.unpack_from("<f", b, o)[0]
        lit = lambda x: ("%.9g" % x) if any(c in ("%.9g" % x) for c in ".e") else ("%.9g.0" % x)
        with open(out, "w", newline="\n") as o:
            o.write("// generated by tools/gen_collide_template.py from a classic level's collision pass (cube on the floor); do not edit\n")
            o.write("#pragma once\nnamespace dp { namespace gdcol { namespace tmpl {\n")
            o.write("inline constexpr size_t kImageBytes = %d;\n" % len(img))
            o.write("inline const char* const kImageHex =\n")
            hexs = img.hex()
            for i in range(0, len(hexs), 120):
                o.write('    "%s"\n' % hexs[i:i + 120])
            o.write("    ;\n")
            o.write("inline constexpr float kSpeedA = %sf, kSpeedB = %sf, kW764 = %sf, kScaleX = %sf, kScaleY = %sf, kCeilWord = %sf;\n"
                    % tuple(lit(v) for v in (f(lay[0], 8), f(lay[0], 12), f(lay[2], 4), f(lay[4], 0), f(lay[4], 4), f(lay[4], 8))))
            o.write("inline constexpr float kMaxPortalY = %sf, kMinPortalY = %sf;\n" % (lit(float(pq[0])), lit(float(pq[1]))))
            o.write("}}}  // namespace dp::gdcol::tmpl\n")
        print("written", out, len(img), "bytes; layer", [x.hex()[:24] for x in lay], pq)
        break
